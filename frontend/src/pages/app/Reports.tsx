import { useState } from "react";
import { Link } from "react-router-dom";
import { Download, FileText } from "lucide-react";
import { api } from "../../lib/api";
import { useAsync } from "../../lib/useAsync";
import {
  Card,
  EmptyState,
  ErrorState,
  RunStatusBadge,
  Spinner,
} from "../../components/ui";
import { formatDateTime } from "../../lib/format";

export function Reports() {
  const assessments = useAsync(() => api.assessments(), []);
  const [severityFilter, setSeverityFilter] = useState("");

  const rows = (assessments.data ?? []).filter((item) => {
    if (!severityFilter || !item.summary) return true;
    const counts = item.summary.findings_by_severity as Record<string, number>;
    return (counts[severityFilter] ?? 0) > 0;
  });

  return (
    <div className="space-y-6">
      <div className="flex flex-wrap items-end justify-between gap-3">
        <div>
          <h1 className="text-xl font-semibold tracking-tight">Reports</h1>
          <p className="mt-1 text-sm text-tx-3">
            Schema-validated JSON and Markdown artifacts generated by the
            existing report engine. Downloads reflect current review state.
          </p>
        </div>
        <select
          aria-label="Filter by severity present"
          className="input w-56"
          value={severityFilter}
          onChange={(event) => setSeverityFilter(event.target.value)}
        >
          <option value="">All reports</option>
          <option value="critical">Contains critical findings</option>
          <option value="high">Contains high findings</option>
          <option value="medium">Contains medium findings</option>
        </select>
      </div>

      <Card>
        {assessments.loading ? (
          <Spinner />
        ) : assessments.error ? (
          <ErrorState message={assessments.error} onRetry={assessments.reload} />
        ) : rows.length === 0 ? (
          <EmptyState
            title="No reports available"
            detail="Reports are generated from completed assessments."
          />
        ) : (
          <ul className="divide-y divide-line">
            {rows.map((item) => (
              <li
                key={item.id}
                className="flex flex-wrap items-center justify-between gap-3 px-5 py-4"
              >
                <div className="min-w-0">
                  <Link
                    to={`/app/assessments/${item.id}`}
                    className="font-mono text-xs text-violet-300 hover:text-violet-200"
                  >
                    {item.id}
                  </Link>
                  <p className="mt-0.5 text-xs text-tx-3">
                    {item.target_name} · {formatDateTime(item.created_at)} ·{" "}
                    {item.summary
                      ? `${item.summary.findings_total} findings / ${item.summary.checks_executed} checks`
                      : "no report yet"}
                  </p>
                </div>
                <div className="flex shrink-0 items-center gap-2">
                  <RunStatusBadge status={item.status} />
                  <button
                    type="button"
                    className="btn-ghost"
                    disabled={!item.summary}
                    onClick={() => void api.downloadReport(item.id, "json")}
                  >
                    <Download className="h-4 w-4" aria-hidden /> JSON
                  </button>
                  <button
                    type="button"
                    className="btn-ghost"
                    disabled={!item.summary}
                    onClick={() => void api.downloadReport(item.id, "markdown")}
                  >
                    <FileText className="h-4 w-4" aria-hidden /> Markdown
                  </button>
                </div>
              </li>
            ))}
          </ul>
        )}
      </Card>
    </div>
  );
}
